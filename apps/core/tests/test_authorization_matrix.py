OBSERVED = {}


@pytest.fixture
def world(basic_client):
    org_a = OrganizationFactory(slug="org-a", name="Org A")
    org_b = OrganizationFactory(slug="org-b", name="Org B")
    Subscription.objects.create(organization=org_a, plan="pro")
